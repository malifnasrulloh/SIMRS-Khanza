    private void BtnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditActionPerformed
        if (TNo.getText().trim().equals("")) {
            Valid.textKosong(TNo, "Kode");
        } else if (TEventName.getText().trim().equals("")) {
            Valid.textKosong(TEventName, "Kategori");
        } else {
            if (tbMaster.getSelectedRow() > -1) {
                if (Sequel.mengedittf("set_cuti", "id=?", "event_name=?,tanggal_awal=?,tanggal_akhir=?,buffer_days_after=?,status=?", 6, new String[]{
                    TEventName.getText(), Valid.SetTgl(DTPTglAwal.getSelectedItem() + ""), Valid.SetTgl(DTPTglAkhir.getSelectedItem() + ""), TBufferDays.getText(), CmbStatus.getSelectedItem().toString(), TNo.getText()
                }) == true) {
                    tampil();
                    emptTeks();
                }
            }
        }
}//GEN-LAST:event_BtnEditActionPerformed

