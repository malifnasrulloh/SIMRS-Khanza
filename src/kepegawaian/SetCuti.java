    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if (TEventName.getText().trim().equals("")) {
            Valid.textKosong(TEventName, "Nama Kegiatan");
        } else if (TBufferDays.getText().trim().equals("") || TBufferDays.getText().matches(".*\\D.*")) {
            Valid.textKosong(TBufferDays, "Buffer Hari");
        } else {
            Sequel.menyimpan("set_cuti", "null,?,?,?,?,?", "Event", 5, new String[]{
                TEventName.getText().trim(),
                Valid.SetTgl(DTPTglAwal.getSelectedItem() + ""),
                Valid.SetTgl(DTPTglAkhir.getSelectedItem() + ""),
                TBufferDays.getText(),
                CmbStatus.getSelectedItem().toString()
            });
            tampil();
            emptTeks();
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

