private void autoNomor() {
        try {
            try {
                ps = koneksi.prepareStatement("select IFNULL((max(id)), 0) from set_cuti");
                rs = ps.executeQuery();
                while (rs.next()) {
                    TNo.setText(String.valueOf(rs.getInt(1) + 1));
                }
            } catch (Exception e) {
                System.out.println("Notif : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
    }

    private void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement(
                    "select * from set_cuti where event_name like ? "
                    + "order by tanggal_awal desc");
            try {
                ps.setString(1, "%" + TCari.getText().trim() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new Object[]{
                        rs.getString(1), rs.getString(2), rs.getString(3),
                        rs.getString(4), rs.getString(5), rs.getString(6)
                    });
                }
                autoNomor();
            } catch (Exception e) {
                System.out.println("Notif : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }

    public void emptTeks() {
        TNo.setText("");
        TEventName.setText("");
        TBufferDays.setText("0");
        CmbStatus.setSelectedIndex(0);
        TCari.setText("");
        TEventName.requestFocus();
        autoNomor();
    }

    private void getData() {
        if (tbMaster.getSelectedRow() != -1) {
            TNo.setText(tbMaster.getValueAt(tbMaster.getSelectedRow(), 0).toString());
            TEventName.setText(tbMaster.getValueAt(tbMaster.getSelectedRow(), 1).toString());
            Valid.SetTgl(DTPTglAwal, tbMaster.getValueAt(tbMaster.getSelectedRow(), 2).toString());
            Valid.SetTgl(DTPTglAkhir, tbMaster.getValueAt(tbMaster.getSelectedRow(), 3).toString());
            TBufferDays.setText(tbMaster.getValueAt(tbMaster.getSelectedRow(), 4).toString());
            CmbStatus.setSelectedItem(tbMaster.getValueAt(tbMaster.getSelectedRow(), 5).toString());
        }
    }

