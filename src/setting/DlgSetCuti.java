    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        switch (TabSetCuti.getSelectedIndex()) {
            case 0:
                String tgl = Valid.SetTgl(DTPTgl.getSelectedItem() + "");
                if (Sequel.cariInteger("select count(*) from pembatasan_cuti where tanggal='" + tgl + "'") > 0) {
                    JOptionPane.showMessageDialog(null, "Maaf, tanggal sudah ada dalam pembatasan cuti ...!!!!");
                } else {
                    Sequel.menyimpan("pembatasan_cuti", "'" + tgl + "'", "Pembatasan Cuti");
                    runBackground(() -> tampilPembatasan());
                }
                break;
            case 1:
                if (tabMode2.getRowCount() == 0) {
                    Sequel.menyimpan("set_pengaturan_cuti", "'" + spMaksPengajuan.getValue() + "','" + spMaksJatah.getValue() + "'", "Pengaturan Cuti");
                    runBackground(() -> tampilPengaturan());
                } else if (tabMode2.getRowCount() > 0) {
                    Sequel.queryu("update set_pengaturan_cuti set maks_pengajuan='" + spMaksPengajuan.getValue() + "', maks_jatah_semester='" + spMaksJatah.getValue() + "'");
                    runBackground(() -> tampilPengaturan());
                }
                break;
            default:
                break;
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

    private void BtnSimpanKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_BtnSimpanKeyPressed
        if (evt.getKeyCode() == KeyEvent.VK_SPACE) {
            BtnSimpanActionPerformed(null);
        } else {
            if (TabSetCuti.getSelectedIndex() == 0) {
                Valid.pindah(evt, DTPTgl, BtnHapus);
            } else if (TabSetCuti.getSelectedIndex() == 1) {
                Valid.pindah(evt, BtnKeluar, BtnHapus);
            }
        }
}//GEN-LAST:event_BtnSimpanKeyPressed

    private void BtnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnHapusActionPerformed
        switch (TabSetCuti.getSelectedIndex()) {
            case 0:
                if (tabMode.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(null, "Maaf, data sudah habis...!!!!");
                    DTPTgl.requestFocus();
                } else if (tbPembatasan.getSelectedRow() != -1) {
                    Sequel.queryu("delete from pembatasan_cuti where tanggal='" + tbPembatasan.getValueAt(tbPembatasan.getSelectedRow(), 0).toString() + "'");
                    runBackground(() -> tampilPembatasan());
                } else {
                    JOptionPane.showMessageDialog(null, "Maaf, silahkan pilih data yang mau dihapus...!!!!");
                }
                break;
            case 1:
                Sequel.queryu("delete from set_pengaturan_cuti");
                runBackground(() -> tampilPengaturan());
                spMaksPengajuan.setValue(0);
                spMaksJatah.setValue(0);
                break;
            default:
                break;
        }
}//GEN-LAST:event_BtnHapusActionPerformed

