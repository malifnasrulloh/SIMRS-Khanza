    private void tampilPembatasan() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement("select tanggal from pembatasan_cuti order by tanggal desc");
            try {
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new Object[]{rs.getString(1)});
                }
            } catch (Exception e) {
                System.out.println("Notifikasi : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
    }

