    private void encounter() {
        //kirim encounter
        try {
            ps = koneksi.prepareStatement(
                    "select reg_periksa.tgl_registrasi,reg_periksa.jam_reg,reg_periksa.no_rawat,pasien.nm_pasien,pasien.no_ktp,"
                    + "pegawai.nama,pegawai.no_ktp as ktpdokter,poliklinik.nm_poli,satu_sehat_mapping_lokasi_ralan.id_lokasi_satusehat,"
                    + "reg_periksa.status_lanjut,concat(reg_periksa.tgl_registrasi,'T',reg_periksa.jam_reg,'+07:00') as pulang,ifnull(satu_sehat_encounter.id_encounter,'') as id_encounter "
                    + "from reg_periksa inner join pasien on reg_periksa.no_rkm_medis=pasien.no_rkm_medis inner join pegawai on pegawai.nik=reg_periksa.kd_dokter "
                    + "inner join poliklinik on reg_periksa.kd_poli=poliklinik.kd_poli inner join satu_sehat_mapping_lokasi_ralan on satu_sehat_mapping_lokasi_ralan.kd_poli=poliklinik.kd_poli "
                    + "left join satu_sehat_encounter on satu_sehat_encounter.no_rawat=reg_periksa.no_rawat "
                    + "where reg_periksa.status_bayar='Sudah Bayar' and reg_periksa.tgl_registrasi between ? and ?");
            try {
                ps.setString(1, Tanggal1.getText());
                ps.setString(2, Tanggal2.getText());
                rs = ps.executeQuery();
                SystemLogger.sql(ps);
                while (rs.next()) {
                    if ((!rs.getString("no_ktp").equals("")) && (!rs.getString("ktpdokter").equals("")) && rs.getString("id_encounter").equals("")) {
                        try {
                            iddokter = satuSehatHelper.getPractitionerIDByNIK(rs.getString("ktpdokter"));
                            idpasien = satuSehatHelper.getPatientIDByNIK(rs.getString("no_ktp"));
                            try {
                                requestJson = FHIRPayload.from(
                                        EncounterService.buildEncounter(
                                                JsonUtil.createObject()
                                                        .put("code_class", rs.getString("status_lanjut").equals("Ralan") ? "AMB" : "IMP")
                                                        .put("display_class", rs.getString("status_lanjut").equals("Ralan") ? "ambulatory" : "inpatient encounter")
                                                        .put("id_pasien", idpasien)
                                                        .put("nm_pasien", rs.getString("nm_pasien"))
                                                        .put("id_dokter", iddokter)
                                                        .put("nama_dokter", rs.getString("nama"))
                                                        .put("tgl_registrasi", rs.getString("tgl_registrasi"))
                                                        .put("jam_reg", rs.getString("jam_reg"))
                                                        .put("pulang", rs.getString("pulang"))
                                                        .put("id_lokasi", rs.getString("id_lokasi_satusehat"))
                                                        .put("nm_poli", rs.getString("nm_poli"))
                                                        .put("no_rawat", rs.getString("no_rawat"))
                                                        .put("service_provider_id", koneksiDB.IDSATUSEHAT())
                                                        .put("status", "arrived")
                                                        .getNode())).toJson();

                                URL = link + "/Encounter";

                                response = exchangeInteroperabilitas(URL, requestJson, HttpMethod.POST);
                                if (response == null) {
                                    throw new IllegalStateException(String.format("Response {'%s'} kosong / null", URL));
                                }

                                responseBody = response.getBody();
                                userTableModel.tambahData("Result JSON : " + responseBody.toString());

                                if (!responseBody.path("id").asString().equals("")) {
                                    Sequel.menyimpan2("satu_sehat_encounter", "?,?", "No.Rawat", 2, new String[]{
                                        rs.getString("no_rawat"), responseBody.path("id").asString()
                                    });
                                }
                            } catch (Exception ea) {
                                userTableModel.tambahData("Notifikasi Bridging : " + ea, LogType.EXCEPTION);
                                SystemLogger.error(ea);
                            }
                        } catch (Exception ef) {
                            System.out.println("Notifikasi : " + ef);
                            SystemLogger.error(ef);
                        }
                    } else {
                        try {
                            iddokter = satuSehatHelper.getPractitionerIDByNIK(rs.getString("ktpdokter"));
                            idpasien = satuSehatHelper.getPatientIDByNIK(rs.getString("no_ktp"));
                            try {
                                requestJson = FHIRPayload.from(
                                        EncounterService.buildEncounter(
                                                JsonUtil.createObject()
                                                        .put("id_encounter", rs.getString("id_encounter"))
                                                        .put("status", "finished")
                                                        .put("code_class", rs.getString("status_lanjut").equals("Ralan") ? "AMB" : "IMP")
                                                        .put("display_class", rs.getString("status_lanjut").equals("Ralan") ? "ambulatory" : "inpatient encounter")
                                                        .put("id_pasien", idpasien)
                                                        .put("nm_pasien", rs.getString("nm_pasien"))
                                                        .put("id_dokter", iddokter)
                                                        .put("nama_dokter", rs.getString("nama"))
                                                        .put("tgl_registrasi", rs.getString("tgl_registrasi"))
                                                        .put("jam_reg", rs.getString("jam_reg"))
                                                        .put("pulang", rs.getString("pulang"))
                                                        .put("id_lokasi", rs.getString("id_lokasi_satusehat"))
                                                        .put("nm_poli", rs.getString("nm_poli"))
                                                        .put("no_rawat", rs.getString("no_rawat"))
                                                        .put("service_provider_id", koneksiDB.IDSATUSEHAT())
                                                        .getNode())).toJson();

                                URL = link + "/Encounter/" + rs.getString("id_encounter");

                                response = exchangeInteroperabilitas(URL, requestJson, HttpMethod.PUT);
                                if (response == null) {
                                    throw new IllegalStateException(String.format("Response {'%s'} kosong / null", URL));
                                }

                                responseBody = response.getBody();
                                userTableModel.tambahData("Result JSON : " + responseBody.toString());

                                if (!responseBody.path("id").asString().equals("")) {
                                    Sequel.menyimpan2("satu_sehat_encounter", "?,?", "No.Rawat", 2, new String[]{
                                        rs.getString("no_rawat"), responseBody.path("id").asString()
                                    });
                                }
                            } catch (Exception ea) {
                                userTableModel.tambahData("Notifikasi Bridging : " + ea, LogType.EXCEPTION);
                                SystemLogger.error(ea);
                            }
                        } catch (Exception ef) {
                            System.out.println("Notifikasi : " + ef);
                            SystemLogger.error(ef);
                        }
                    }
                }
            } catch (Exception ex) {
                System.out.println("Notif : " + ex);
                SystemLogger.error(ex);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception ez) {
            System.out.println("Notifikasi : " + ez);
            SystemLogger.error(ez);
        }
    }

