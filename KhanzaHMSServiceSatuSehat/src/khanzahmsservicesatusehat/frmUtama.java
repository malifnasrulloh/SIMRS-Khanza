    private ResponseEntity<JsonNode> exchangeInteroperabilitas(String URL, String requestJson, HttpMethod httpMethod) {
        try {
            headers = new HttpHeaders();
            headers.setContentType(MediaType.APPLICATION_JSON);
            headers.add("Authorization", "Bearer " + satuSehatHelper.getAuthToken());

            HttpRequestUtil http = HttpRequestUtil.getInstance();
            ResponseEntity<JsonNode> responseEntity = http.exchange(URL, httpMethod, requestJson, JsonNode.class, headers);

            if (responseEntity == null) {
                return null;
            }

            userTableModel.tambahData("Request URL: " + URL, LogType.HTTP);
            userTableModel.tambahData("Request JSON: " + requestJson, LogType.HTTP);

            return responseEntity;
        } catch (Exception e) {
            return null;
        }
    }

